/// A country's name by its code, in Vietnamese or English; None for a code not in the list.
pub fn name(cc: &str, vietnamese: bool) -> Option<&'static str> {
    let cc = cc.trim().to_ascii_uppercase();
    ALL.iter().find(|(code, _, _)| *code == cc).map(|(_, en, vi)| if vietnamese { *vi } else { *en })
}

/// Its English name (a server's city is compared with it: "Singapore · Singapore" is said once).
pub fn english(cc: &str) -> Option<&'static str> {
    name(cc, false)
}

/// Every code listed (the words suite checks the list).
pub fn codes() -> impl Iterator<Item = &'static str> {
    ALL.iter().map(|(code, _, _)| *code)
}
